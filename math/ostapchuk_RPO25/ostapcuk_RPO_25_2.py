
import math
import random


# ------------------------------------------------------------
# Переход из алгебраической формы (a, b) в полярную (r, phi).
# r — модуль, phi — аргумент (угол от положительного направления оси X).
# Используем math.atan2(b, a), а не arctan(b/a):
# atan2 корректно работает во всех четвертях и при a = 0.
# ------------------------------------------------------------
def to_polar(a, b):
    r = math.sqrt(a * a + b * b)
    phi = math.atan2(b, a)
    return r, phi


# ------------------------------------------------------------
# Обратный переход: из полярной формы (r, phi) в алгебраическую (a, b).
# Это и есть тригонометрическая запись:
#     a = r * cos(phi),   b = r * sin(phi)
# ------------------------------------------------------------
def to_algebraic(r, phi):
    a = r * math.cos(phi)
    b = r * math.sin(phi)
    return a, b


# ------------------------------------------------------------
# Умножение двух комплексных чисел, заданных парой (a, b).
# Формула: (a1 + b1*i)(a2 + b2*i) =
#          (a1*a2 - b1*b2) + (a1*b2 + b1*a2)*i
# Здесь i^2 = -1, поэтому произведение мнимых частей даёт
# слагаемое -b1*b2 в действительной части.
# ------------------------------------------------------------
def multiply(z1, z2):
    a1, b1 = z1
    a2, b2 = z2
    return (a1 * a2 - b1 * b2, a1 * b2 + b1 * a2)


# ------------------------------------------------------------
# Возведение в степень "в лоб": n последовательных умножений.
# Это эталон, с которым будем сравнивать формулу Муавра.
# Работает без cmath и без оператора ** для комплексных чисел.
# ------------------------------------------------------------
def power_iterative(a, b, n):
    result = (1.0, 0.0)  # нейтральный элемент по умножению: 1 + 0i
    base = (a, b)
    for _ in range(n):
        result = multiply(result, base)
    return result


# ------------------------------------------------------------
# Возведение в степень по формуле Муавра:
#     z^n = r^n * (cos(n*phi) + i*sin(n*phi)).
# Сначала переводим число в полярную форму, затем
# модуль возводим в степень через math.pow,
# а угол умножаем на n, после чего возвращаемся
# в алгебраическую форму.
# ------------------------------------------------------------
def mawr(a, b, n):
    r, phi = to_polar(a, b)
    r_n = math.pow(r, n)
    return to_algebraic(r_n, phi * n)


# ------------------------------------------------------------
# Один шаг индукции для случайного комплексного числа z и шага k.
# Проверяем три вещи:
#   1) z^k, посчитанное итеративно, совпадает с формулой Муавра;
#   2) z^(k+1), посчитанное итеративно, совпадает с формулой Муавра;
#   3) z^(k+1) получается умножением z^k на z —
#      это и есть суть индукционного перехода k -> k+1.
# Возвращаем словарь со всеми промежуточными значениями,
# чтобы потом напечатать их и сравнить.
# ------------------------------------------------------------
def induction_step(k):
    a = random.uniform(-3, 3)
    b = random.uniform(-3, 3)

    # Итеративное возведение в степени k и k+1
    z_k = power_iterative(a, b, k)
    z_k1 = power_iterative(a, b, k + 1)

    # Те же степени, но через формулу Муавра
    r, phi = to_polar(a, b)
    z_k_formula = to_algebraic(math.pow(r, k), phi * k)
    z_k1_formula = to_algebraic(math.pow(r, k + 1), phi * (k + 1))

    # Индукционный переход: z^(k+1) = z^k * z
    z_k1_from_step = multiply(z_k, (a, b))

    return {
        "k": k,
        "z": (a, b),
        "z_k_iter": z_k,
        "z_k_formula": z_k_formula,
        "z_k1_iter": z_k1,
        "z_k1_formula": z_k1_formula,
        "z_k1_from_step": z_k1_from_step,
    }


# ------------------------------------------------------------
# Сравнение двух комплексных чисел с заданной точностью.
# Из-за погрешности float нельзя сравнивать через ==,
# поэтому проверяем, что разности действительных и мнимых
# частей меньше tol.
# ------------------------------------------------------------
def check_equality(x, y, tol=1e-9):
    return abs(x[0] - y[0]) < tol and abs(x[1] - y[1]) < tol


# ------------------------------------------------------------
# Прогон нескольких случайных тестов.
# Для каждого k печатаем все значения и проверяем три равенства.
# Если хотя бы одно не выполняется — assert останавливает программу.
# ------------------------------------------------------------
def run_induction_check(trials=5):
    print("Индукционная проверка формулы Муавра")
    print("-" * 60)
    for _ in range(trials):
        k = random.randint(1, 8)
        res = induction_step(k)
        a, b = res["z"]

        print(f"k = {k}, z = {a:.4f} + {b:.4f}i")

        # Проверка базы: z^k итеративно == z^k по Муавру
        print(f"  z^k   (итеративно): ({res['z_k_iter'][0]:.6f}, {res['z_k_iter'][1]:.6f})")
        print(f"  z^k   (Муавр):      ({res['z_k_formula'][0]:.6f}, {res['z_k_formula'][1]:.6f})")
        assert check_equality(res["z_k_iter"], res["z_k_formula"]), "z^k не совпало"

        # Проверка формулы на шаге k+1
        print(f"  z^(k+1) (итеративно): ({res['z_k1_iter'][0]:.6f}, {res['z_k1_iter'][1]:.6f})")
        print(f"  z^(k+1) (Муавр):      ({res['z_k1_formula'][0]:.6f}, {res['z_k1_formula'][1]:.6f})")

        # Проверка самого индукционного перехода
        print(f"  z^(k+1) = z^k * z:    ({res['z_k1_from_step'][0]:.6f}, {res['z_k1_from_step'][1]:.6f})")
        assert check_equality(res["z_k1_iter"], res["z_k1_formula"]), "z^(k+1) не совпало"
        assert check_equality(res["z_k1_iter"], res["z_k1_from_step"]), "переход k -> k+1 не совпал"

        print("  OK")
        print()


# ------------------------------------------------------------
# Дополнительное задание: Ханойская башня.
# Рекурсивный алгоритм: чтобы перенести n дисков со source на target,
#   1) переносим n-1 диск с source на auxiliary,
#   2) переносим самый большой диск с source на target,
#   3) переносим n-1 диск с auxiliary на target.
# Базовый случай: n = 1 — просто один ход.
# ------------------------------------------------------------
def hanoi(n, source, target, auxiliary, moves):
    if n == 1:
        moves.append((source, target))
        return
    hanoi(n - 1, source, auxiliary, target, moves)
    moves.append((source, target))
    hanoi(n - 1, auxiliary, target, source, moves)


def solve_hanoi(n):
    moves = []
    hanoi(n, "A", "C", "B", moves)
    return moves


if __name__ == "__main__":
    # Запуск индукционной проверки формулы Муавра
    run_induction_check()

