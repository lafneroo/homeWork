    n = int(input("Введите число дисков N: "))
    moves = solve_hanoi(n)
    for i, (src, dst) in enumerate(moves, 1):
        print(f"{i}. {src} -> {dst}")
    print(f"Всего ходов: {len(moves)} (ожидаем {2**n - 1})")